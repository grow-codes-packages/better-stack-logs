"""Live checks of the Python package against the real Better Stack Logs service (GRO-1385).

Service-owned (not generated by sdk-kit). It verifies what the stub-based Docker suite cannot
(``docs/compatibility.md``, "Live SaaS checks"): it ingests events with a unique marker as JSON,
NDJSON, MessagePack, OTLP protobuf, OTLP JSON and through the batching log client, reads them back
over the SQL API (``wait_for_log``, ``search_logs``, ``search`` with a cursor, ``query`` with
server-side bound parameters that contain a backslash, quotes and a tab), and checks ``health``
and ``ping`` on both hosts, the error mapping of wrong credentials and of a missing table.

Environment (the same names as the GitHub organisation secrets; all six are required):

    BETTERSTACK_INGEST_HOST      the source's ingesting host (s1234.eu-nbg-2.betterstackdata.com)
    BETTERSTACK_SOURCE_TOKEN     the source token
    BETTERSTACK_QUERY_HOST       the SQL connection host (eu-nbg-2-connect.betterstackdata.com)
    BETTERSTACK_QUERY_USER       the SQL connection user name
    BETTERSTACK_QUERY_PASSWORD   the SQL connection password
    BETTERSTACK_SOURCE_TABLE     the source's table name (t1234_grow_sdk_live)
    LIVE_TIMEOUT_S               how long to wait for an event to become queryable, default 300

Without them it prints ``skipped: no credentials`` and exits 0. Run it with ``make -C live live``
(installs ``./python`` into ``live/.venv``). ``--check-credentials`` only reports whether the
variables are set (exit 0) or not (exit 78) and never imports the SDK.

The SQL API allows 4 concurrent queries per account, so every query here runs one after another.
"""

from __future__ import annotations

import os
import sys
import time
import uuid
from collections.abc import Callable, Iterable, Mapping
from datetime import datetime, timedelta, timezone
from typing import Any

REQUIRED_ENV = (
    "BETTERSTACK_INGEST_HOST",
    "BETTERSTACK_SOURCE_TOKEN",
    "BETTERSTACK_QUERY_HOST",
    "BETTERSTACK_QUERY_USER",
    "BETTERSTACK_QUERY_PASSWORD",
    "BETTERSTACK_SOURCE_TABLE",
)
EXIT_SKIPPED = 78  # EX_CONFIG: only used by --check-credentials
# A bound parameter value with every character ClickHouse's TSV parameter format escapes or that
# breaks naive quoting: backslashes, double and single quotes, a tab.
TRICKY = "C:\\grow\\live \"double\" 'single'\ttab"
KINDS = ("json", "ndjson", "msgpack", "otlp-protobuf", "otlp-json", "log-client")


# --------------------------------------------------------------------------- harness


class CheckFailedError(AssertionError):
    """An expectation of a live check did not hold."""


def expect(condition: object, message: str) -> None:
    """Raise :class:`CheckFailedError` with ``message`` unless ``condition`` is truthy."""
    if not condition:
        raise CheckFailedError(message)


def poll(fn: Callable[[], Any], *, timeout_s: float, interval_s: float, what: str) -> Any:
    """Call ``fn`` until it returns a truthy value; builtin ``TimeoutError`` at the deadline."""
    deadline = time.monotonic() + timeout_s
    while True:
        value = fn()
        if value:
            return value
        if time.monotonic() + interval_s > deadline:
            raise TimeoutError(f"{what}: not seen within {timeout_s:.0f} s")
        time.sleep(interval_s)


def _annotation(text: str) -> str:
    return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


class Suite:
    """Runs named checks in order and records PASS, FAIL, WARN or SKIP for each."""

    def __init__(self, title: str) -> None:
        self.title = title
        self.results: list[tuple[str, str, str]] = []
        self.passed: set[str] = set()
        self.github = os.environ.get("GITHUB_ACTIONS") == "true"

    def check(
        self,
        name: str,
        fn: Callable[[], Any],
        *,
        needs: Iterable[str] = (),
        warn_only: bool = False,
    ) -> Any:
        """Run ``fn``; a check whose ``needs`` did not pass is skipped. Returns ``fn()``."""
        missing = [n for n in needs if n not in self.passed]
        if missing:
            self._record("SKIP", name, "needs " + ", ".join(missing))
            return None
        started = time.monotonic()
        try:
            value = fn()
        except Exception as err:  # noqa: BLE001 - every failure is reported, the suite goes on
            status = "WARN" if warn_only else "FAIL"
            self._record(status, name, f"{type(err).__name__}: {err}")
            return None
        self.passed.add(name)
        self._record("PASS", name, f"{time.monotonic() - started:.1f} s")
        return value

    def _record(self, status: str, name: str, detail: str) -> None:
        self.results.append((status, name, detail))
        print(f"{status:4} {name} ({detail})", flush=True)
        if self.github and status in ("FAIL", "WARN"):
            level = "error" if status == "FAIL" else "warning"
            print(f"::{level} title=live: {_annotation(name)}::{_annotation(detail)}", flush=True)

    def finish(self) -> int:
        """Print the summary (and the GitHub step summary); 1 when a check failed."""
        counts = {s: sum(1 for r in self.results if r[0] == s) for s in ("PASS", "FAIL", "WARN")}
        counts["SKIP"] = len(self.results) - sum(counts.values())
        line = ", ".join(f"{n} {s.lower()}" for s, n in counts.items())
        print(f"\n{self.title}: {line}", flush=True)
        summary = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary:
            rows = "\n".join(f"| {s} | {n} | {d.replace('|', '/')} |" for s, n, d in self.results)
            with open(summary, "a", encoding="utf-8") as fh:
                fh.write(f"### {self.title}\n\n{line}\n\n| Result | Check | Detail |\n")
                fh.write(f"| - | - | - |\n{rows}\n\n")
        return 1 if counts["FAIL"] else 0


def info(text: str) -> None:
    """An informational line under the current check."""
    print(f"     {text}", flush=True)


def missing_credentials(environ: Mapping[str, str]) -> list[str]:
    """Names of the required variables that are unset or empty."""
    return [name for name in REQUIRED_ENV if not environ.get(name, "").strip()]


# --------------------------------------------------------------------------- live checks


def run() -> int:
    """All live checks; returns the exit code."""
    import grow_better_stack_logs as sdk

    timeout_s = float(os.environ.get("LIVE_TIMEOUT_S", "") or 300)
    marker = f"growlive{uuid.uuid4().hex[:16]}"
    table = os.environ["BETTERSTACK_SOURCE_TABLE"].strip()
    ingest = {
        "BETTERSTACK_INGESTING_HOST": os.environ["BETTERSTACK_INGEST_HOST"].strip(),
        "BETTERSTACK_SOURCE_TOKEN": os.environ["BETTERSTACK_SOURCE_TOKEN"].strip(),
    }
    sql = {
        "BETTERSTACK_QUERY_HOST": os.environ["BETTERSTACK_QUERY_HOST"].strip(),
        "BETTERSTACK_QUERY_USERNAME": os.environ["BETTERSTACK_QUERY_USER"].strip(),
        "BETTERSTACK_QUERY_PASSWORD": os.environ["BETTERSTACK_QUERY_PASSWORD"].strip(),
        "BETTERSTACK_SOURCE_TABLE": table,
    }
    suite = Suite(f"better-stack-logs live checks (Python {sdk.__version__})")
    print(f"marker {marker}, table {table}\n", flush=True)
    state: dict[str, Any] = {}

    def build() -> None:
        client = sdk.BetterStackClient.from_env({**ingest, **sql})
        info(f"ingest {client.config.url}, sql {client.config.query_url}")
        state["client"] = client
        state["ingest_only"] = sdk.BetterStackClient.from_env(ingest)
        state["query_only"] = sdk.BetterStackClient.from_env(sql)

    suite.check("config + clients (both sides, ingest only, query only)", build)
    if "client" not in state:
        return suite.finish()
    client: Any = state["client"]
    ingest_only: Any = state["ingest_only"]
    query_only: Any = state["query_only"]

    with client, ingest_only, query_only:

        def health(side: Any, endpoint: str) -> Callable[[], None]:
            def check() -> None:
                status = side.health()
                info(f"{status.status} {dict(status.details)}")
                expect(status.healthy, f"not healthy: {status}")
                expect(status.details.get("endpoint") == endpoint, f"endpoint {status.details}")

            return check

        def ping(side: Any) -> Callable[[], None]:
            return lambda: info(f"{side.ping():.0f} ms")

        def wrong(env: Mapping[str, str], name: str) -> Callable[[], None]:
            def check() -> None:
                with sdk.BetterStackClient.from_env(env) as other:
                    try:
                        other.ping()
                    except sdk.AuthenticationError as err:
                        info(f"HTTP {err.http_status}")
                        return
                raise CheckFailedError(f"a wrong {name} was accepted")

            return check

        suite.check("health (SQL host, GET /ping)", health(query_only, "query"))
        suite.check("health (ingest host, GET /)", health(ingest_only, "ingest"))
        suite.check("ping (SQL host, SELECT count() ... WHERE 1 = 0)", ping(query_only))
        suite.check("ping (ingest host, empty batch [])", ping(ingest_only))
        wrong_token = {**ingest, "BETTERSTACK_SOURCE_TOKEN": "grow-live-wrong-token"}
        suite.check("ping (wrong source token -> AUTHENTICATION)", wrong(wrong_token, "token"))
        wrong_password = {**sql, "BETTERSTACK_QUERY_PASSWORD": "grow-live-wrong-password"}
        suite.check(
            "ping (wrong SQL password -> AUTHENTICATION)", wrong(wrong_password, "password")
        )

        def unsupported() -> None:
            for name, fn in (
                ("server_version", client.server_version),
                ("list_labels", client.query().list_labels),
            ):
                try:
                    fn()
                except sdk.UnsupportedError:
                    continue
                raise CheckFailedError(f"{name}() did not raise UnsupportedError")
            expect(client.query().list_streams() == [table], "list_streams != [source_table]")

        suite.check("server_version / list_labels -> UNSUPPORTED, list_streams", unsupported)
        q: Any = client.query()
        # Hot storage of the source; source_table is validated as an identifier by the config.
        hot = f"remote({client.config.source_table}_logs)"

        def echo() -> None:
            rows = q.query("SELECT {s:String} AS s, {n:UInt32} AS n", {"s": TRICKY, "n": 7})
            info(f"{rows}")
            expect(len(rows) == 1 and rows[0]["s"] == TRICKY, f"echo returned {rows!r}")
            expect(str(rows[0]["n"]) == "7", f"UInt32 echo returned {rows[0]['n']!r}")

        suite.check("query: bound String with backslash, quotes, tab (echo)", echo)

        def raw() -> None:
            text = q.query_raw("SELECT 1 AS one FORMAT TabSeparated")
            expect(text.strip() == "1", f"query_raw returned {text!r}")

        suite.check("query_raw (FORMAT TabSeparated)", raw)

        def missing_table() -> None:
            try:
                missing = f"t0_grow_live_missing_{marker}_logs"
                q.query(f"SELECT dt FROM remote({missing}) LIMIT 1")  # noqa: S608 - fixed name
            except sdk.NotFoundError as err:
                info(f"{err.code} HTTP {err.http_status}")
                return
            raise CheckFailedError("a missing table did not raise NotFoundError")

        suite.check("query on a missing table -> NOT_FOUND", missing_table)

        # ------------------------------------------------------------------ ingest

        def event(kind: str) -> dict[str, Any]:
            return {
                "message": f"{marker} {kind}",
                "dt": datetime.now(timezone.utc),
                "grow_live_marker": marker,
                "grow_live_kind": kind,
                "grow_live_tricky": TRICKY,
            }

        def raw_ingest(kind: str) -> Callable[[], None]:
            def check() -> None:
                state.setdefault("sent_at", time.monotonic())
                state.setdefault("start", datetime.now(timezone.utc) - timedelta(minutes=5))
                exporter = client.new_exporter(encoding=kind)
                exporter.send_events([event(kind)])

            return check

        def record(kind: str) -> Any:
            return sdk.LogRecord(
                body=f"{marker} {kind}",
                severity=sdk.Severity.WARN,
                attributes={"grow_live_marker": marker, "grow_live_kind": kind},
                resource={"service.name": "grow-sdk-live-python"},
            )

        def otlp_ingest(protocol: str) -> Callable[[], None]:
            def check() -> None:
                state.setdefault("sent_at", time.monotonic())
                state.setdefault("start", datetime.now(timezone.utc) - timedelta(minutes=5))
                exporter = client.new_otlp_exporter(protocol=protocol)
                result = exporter.export([record(f"otlp-{protocol}")])
                expect(result.accepted == 1 and result.error is None, f"export: {result}")

            return check

        def log_client() -> None:
            logs = client.log_client(options=sdk.BatchOptions(flush_interval_s=0.5))
            logs.logger("grow.live").info(f"{marker} log-client", {"grow_live_marker": marker})
            logs.flush(30)
            stats = logs.stats()
            info(f"{stats}")
            expect(stats.sent == 1 and stats.failed == 0 and stats.dropped == 0, f"{stats}")

        suite.check("ingest JSON (gzip)", raw_ingest("json"))
        suite.check("ingest NDJSON (gzip)", raw_ingest("ndjson"))
        suite.check("ingest MessagePack (gzip)", raw_ingest("msgpack"))
        suite.check("ingest OTLP protobuf", otlp_ingest("protobuf"))
        suite.check("ingest OTLP JSON", otlp_ingest("json"))
        suite.check("ingest through the log client (logger)", log_client)

        # ------------------------------------------------------------------ read back

        def wait_for_log() -> None:
            found = q.wait_for_log(f"{marker} json", timeout_s=timeout_s, interval_s=3)
            delay = time.monotonic() - state["sent_at"]
            info(f"queryable after {delay:.0f} s: {found.body!r} at {found.timestamp}")
            expect(found.body == f"{marker} json", f"wait_for_log returned {found.body!r}")

        suite.check("wait_for_log (JSON event)", wait_for_log, needs=["ingest JSON (gzip)"])
        found = ["wait_for_log (JSON event)"]

        def search_logs() -> None:
            def all_kinds() -> Any:
                page = q.search_logs(contains=marker, start=state["start"], limit=100)
                seen = {k for k in KINDS for r in page.records if r.body.endswith(f" {k}")}
                state["seen"] = seen
                return page if seen == set(KINDS) else None

            try:
                page = poll(all_kinds, timeout_s=180, interval_s=5, what="all 6 ingest paths")
            except TimeoutError:
                missing = sorted(set(KINDS) - state.get("seen", set()))
                raise CheckFailedError(f"never found: {', '.join(missing)}") from None
            info(f"{len(page.records)} records: " + ", ".join(r.body for r in page.records))
            expect(len(page.records) >= len(KINDS), "fewer records than ingest paths")

        suite.check("search_logs (all 6 ingest paths)", search_logs, needs=found)

        def search_paged() -> None:
            first = q.search(marker, start=state["start"], limit=2, order="asc")
            expect(len(first.records) == 2 and first.next_cursor, f"page 1: {first}")
            second = q.search(
                marker, start=state["start"], limit=2, order="asc", cursor=first.next_cursor
            )
            bodies = [r.body for r in first.records], [r.body for r in second.records]
            expect(len(bodies[1]) == 2 and not set(bodies[0]) & set(bodies[1]), f"{bodies}")

        suite.check("search (category API, 2 per page + cursor)", search_paged, needs=found)

        def bound_stored() -> None:
            rows = q.query(
                "SELECT JSONExtractString(raw, 'grow_live_tricky') AS v "  # noqa: S608 - see hot
                f"FROM {hot} "
                "WHERE dt > now() - INTERVAL 1 HOUR AND position(raw, {m:String}) > 0 "
                "AND JSONExtractString(raw, 'grow_live_tricky') = {v:String}",
                {"m": marker, "v": TRICKY},
            )
            info(f"{len(rows)} rows")
            expect(rows and all(r["v"] == TRICKY for r in rows), f"rows {rows!r}")

        suite.check(
            "query: bound backslash/quote value matches the stored event", bound_stored, needs=found
        )

        def count() -> None:
            rows = q.query(
                f"SELECT count() AS c FROM {hot} "  # noqa: S608 - validated identifier
                "WHERE dt > now() - INTERVAL 1 HOUR AND position(raw, {m:String}) > 0",
                {"m": marker},
            )
            info(f"{rows}")
            expect(int(rows[0]["c"]) >= len(KINDS), f"count {rows}")

        suite.check(
            "query: count() by marker (64-bit as string)",
            count,
            needs=["search_logs (all 6 ingest paths)"],
        )

    return suite.finish()


def main(argv: list[str]) -> int:
    missing = missing_credentials(os.environ)
    if missing:
        print(f"skipped: no credentials ({', '.join(missing)} not set); live checks not run")
        return EXIT_SKIPPED if "--check-credentials" in argv else 0
    if "--check-credentials" in argv:
        print("credentials: set")
        return 0
    return run()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
